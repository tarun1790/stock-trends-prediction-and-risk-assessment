"""
Quantitative Strategy Simulator & Backtesting Engine.
Calculates Portfolio Equity Curves, Cumulative Return, Sharpe/Sortino Ratios,
Max Drawdown, Win Rate, and Alpha/Beta against Buy & Hold benchmark.
"""

from typing import Any, Dict, List, Optional, Union
import numpy as np
import pandas as pd


class BacktestEngine:
    """
    Simulates real-world execution of trading signals generated by ML/DL models.
    """

    def __init__(
        self,
        initial_capital: float = 100000.0,
        transaction_cost_pct: float = 0.001,  # 0.1% per trade
        risk_free_rate: float = 0.02,        # 2% annual risk-free rate
        periods_per_year: int = 252,
    ):
        self.initial_capital = initial_capital
        self.transaction_cost_pct = transaction_cost_pct
        self.risk_free_rate = risk_free_rate
        self.periods_per_year = periods_per_year

    def run_backtest(
        self,
        prices: Union[pd.Series, np.ndarray],
        signals: Union[pd.Series, np.ndarray],
        dates: Optional[Union[pd.DatetimeIndex, List[Any]]] = None,
        allow_short: bool = False,
    ) -> Dict[str, Any]:
        """
        Execute backtest simulation.

        Args:
            prices: Array or Series of actual asset closing prices.
            signals: Model predicted signals: 1 (Up / Buy), 0 (Down / Cash / Short).
            dates: Optional date index for time series equity curves.
            allow_short: Whether 0 signal enters short position (-1) instead of cash (0).

        Returns:
            Dictionary with performance statistics, trade log, and equity curves.
        """
        p = np.asarray(prices, dtype=np.float64)
        s = np.asarray(signals, dtype=np.float64)

        if len(p) != len(s):
            raise ValueError(
                f"Mismatch in prices length ({len(p)}) and signals length ({len(s)})"
            )

        n = len(p)
        if n < 2:
            raise ValueError("At least 2 price steps required for backtesting.")

        # Price returns: r_t = (P_t - P_{t-1}) / P_{t-1}
        price_returns = np.diff(p) / p[:-1]

        # Positions: shift signals by 1 to prevent lookahead bias
        # Signal at day t dictates position held for day t+1 return
        raw_positions = s[:-1]
        if allow_short:
            positions = np.where(raw_positions == 1, 1.0, -1.0)
        else:
            positions = np.where(raw_positions == 1, 1.0, 0.0)

        # Detect position changes for transaction costs
        pos_changes = np.abs(np.diff(np.insert(positions, 0, 0.0)))
        tx_costs = pos_changes * self.transaction_cost_pct

        # Strategy returns
        strategy_returns = (positions * price_returns) - tx_costs

        # Cumulative Wealth Curves
        strategy_wealth = self.initial_capital * np.cumprod(1.0 + strategy_returns)
        strategy_wealth = np.insert(strategy_wealth, 0, self.initial_capital)

        benchmark_returns = price_returns
        benchmark_wealth = self.initial_capital * np.cumprod(1.0 + benchmark_returns)
        benchmark_wealth = np.insert(benchmark_wealth, 0, self.initial_capital)

        # Performance KPIs
        total_return_strat = float((strategy_wealth[-1] - self.initial_capital) / self.initial_capital)
        total_return_bench = float((benchmark_wealth[-1] - self.initial_capital) / self.initial_capital)

        # Annualized metrics
        years = n / self.periods_per_year
        cagr_strat = float((strategy_wealth[-1] / self.initial_capital) ** (1.0 / max(years, 0.01)) - 1.0) if strategy_wealth[-1] > 0 else -1.0
        cagr_bench = float((benchmark_wealth[-1] / self.initial_capital) ** (1.0 / max(years, 0.01)) - 1.0) if benchmark_wealth[-1] > 0 else -1.0

        ann_vol_strat = float(np.std(strategy_returns) * np.sqrt(self.periods_per_year))
        ann_vol_bench = float(np.std(benchmark_returns) * np.sqrt(self.periods_per_year))

        rf_daily = self.risk_free_rate / self.periods_per_year
        excess_strat = strategy_returns - rf_daily
        sharpe_strat = float(
            (np.mean(excess_strat) / (np.std(strategy_returns) + 1e-9)) * np.sqrt(self.periods_per_year)
        )

        downside_diff = np.minimum(strategy_returns - rf_daily, 0.0)
        downside_std = np.std(downside_diff)
        sortino_strat = float(
            (np.mean(excess_strat) / (downside_std + 1e-9)) * np.sqrt(self.periods_per_year)
        )

        # Max Drawdown
        peak = np.maximum.accumulate(strategy_wealth)
        drawdowns = (strategy_wealth - peak) / peak
        max_drawdown = float(np.min(drawdowns))

        peak_b = np.maximum.accumulate(benchmark_wealth)
        drawdowns_b = (benchmark_wealth - peak_b) / peak_b
        max_drawdown_bench = float(np.min(drawdowns_b))

        # Trade analytics
        trade_signals = np.diff(np.insert(positions, 0, 0.0))
        num_trades = int(np.sum(np.abs(trade_signals) > 0))

        # Win rate on active return periods
        active_returns = strategy_returns[positions != 0]
        win_rate = float(np.mean(active_returns > 0)) if len(active_returns) > 0 else 0.0

        gross_profits = np.sum(active_returns[active_returns > 0]) if len(active_returns) > 0 else 0.0
        gross_losses = np.abs(np.sum(active_returns[active_returns < 0])) if len(active_returns) > 0 else 0.0
        profit_factor = float(gross_profits / (gross_losses + 1e-9)) if gross_losses > 0 else float("inf")

        # Alpha / Beta vs Benchmark
        cov_matrix = np.cov(strategy_returns, benchmark_returns)
        var_bench = np.var(benchmark_returns)
        beta = float(cov_matrix[0, 1] / (var_bench + 1e-9))
        alpha = float((cagr_strat - self.risk_free_rate) - beta * (cagr_bench - self.risk_free_rate))

        date_strings = []
        if dates is not None and len(dates) == n:
            date_strings = [str(d)[:10] for d in dates]
        else:
            date_strings = [f"Day_{i}" for i in range(n)]

        return {
            "metrics": {
                "initial_capital": self.initial_capital,
                "final_portfolio_value": round(float(strategy_wealth[-1]), 2),
                "strategy_total_return_pct": round(total_return_strat * 100.0, 2),
                "benchmark_total_return_pct": round(total_return_bench * 100.0, 2),
                "strategy_cagr_pct": round(cagr_strat * 100.0, 2),
                "benchmark_cagr_pct": round(cagr_bench * 100.0, 2),
                "sharpe_ratio": round(sharpe_strat, 2),
                "sortino_ratio": round(sortino_strat, 2),
                "max_drawdown_pct": round(max_drawdown * 100.0, 2),
                "benchmark_max_drawdown_pct": round(max_drawdown_bench * 100.0, 2),
                "annualized_volatility_pct": round(ann_vol_strat * 100.0, 2),
                "win_rate_pct": round(win_rate * 100.0, 2),
                "profit_factor": round(profit_factor, 2) if profit_factor != float("inf") else 999.0,
                "num_trades": num_trades,
                "alpha": round(alpha, 4),
                "beta": round(beta, 2),
            },
            "equity_curve": {
                "dates": date_strings,
                "strategy_wealth": [round(float(w), 2) for w in strategy_wealth],
                "benchmark_wealth": [round(float(w), 2) for w in benchmark_wealth],
                "drawdowns": [round(float(dd) * 100.0, 2) for dd in drawdowns],
            },
        }
